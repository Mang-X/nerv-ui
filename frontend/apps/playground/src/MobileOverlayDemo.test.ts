it('keeps one dropdown open, receives the typed value and controls collapse slots from the host', async () => {
  wrapper = mount(MobileOverlayDemo, { attachTo: document.body })
  await click('时段')
  expect(body().findAll('.nv-m-ddm-panel')).toHaveLength(1)
  await click('节奏')
  expect(body().findAll('.nv-m-ddm-panel')).toHaveLength(1)
  expect(
    body()
      .findAll('.nv-m-ddm-trigger')
      .map((b) => b.attributes('aria-expanded')),
  ).toEqual(['false', 'true'])
  await click('慢慢来')
  expect(wrapper.get('[aria-label="筛选回显"]').text()).toBe('未选时段 · 2 · change：number 2')
  await click('时段')
  await body().get('.nv-m-ddm-scrim').trigger('click')
  expect(body().findAll('.nv-m-ddm-panel')).toHaveLength(0)
  await click('随行提示')
  expect(wrapper.get('[aria-label="提示展开状态"]').text()).toBe('提示已展开')
  expect(wrapper.get('[data-slot="collapse"]').text()).toContain('留出空白，也是一种安排。')
  await click('收起提示')
  expect(wrapper.get('[data-slot="collapse"] button').attributes('aria-expanded')).toBe('false')
})
it('removes all teleported layers when the overlay page is unmounted', async () => {
  wrapper = mount(MobileOverlayDemo, { attachTo: document.body })
  await click('写下安排')
  await body().get('input#arrangement-duration').trigger('click')
  await settle()
  expect(body().find('[data-slot="number-keyboard"]').exists()).toBe(true)
  wrapper.unmount()
  await settle()
  expect(body().find('[role="dialog"]').exists()).toBe(false)
  expect(body().find('[data-mobile-overlay-layer]').exists()).toBe(false)
  expect(document.body.style.pointerEvents).not.toBe('none')
})
