import { mount, type VueWrapper } from '@vue/test-utils'
import { afterEach, expect, it, vi } from 'vitest'
import MobileFeedbackDemo from './MobileFeedbackDemo.vue'
let wrapper: VueWrapper
async function click(text: string) {
  const button = wrapper.findAll('button').find((b) => b.text() === text)
  expect(button, text).toBeDefined()
  await button!.trigger('click')
}
afterEach(() => {
  wrapper?.unmount()
  document.body.innerHTML = ''
  localStorage.clear()
  vi.useRealTimers()
})
it('opens notice details, dismisses the notice and restores it through host actions', async () => {
  wrapper = mount(MobileFeedbackDemo)
  await click('查看通知')
  expect(wrapper.get('[aria-label="通知回显"]').text()).toBe('下一次散步安排在周六下午。')
  await click('关闭通知')
  expect(wrapper.find('[data-slot="notice-bar"]').exists()).toBe(false)
  await click('恢复通知')
  expect(wrapper.get('[data-slot="notice-bar"]').text()).toContain('周末一起去看风景')
})
it('separates empty, pending, retry failure and successful results with actual retry counts', async () => {
  vi.useFakeTimers()
  wrapper = mount(MobileFeedbackDemo)
  expect(wrapper.get('[data-slot="empty"]').text()).toContain('尚未收集回响')
  await click('收集回响')
  expect(wrapper.get('[aria-label="收集状态"]').text()).toBe('收集中 · 请求 1 次')
  await vi.advanceTimersByTimeAsync(700)
  expect(wrapper.get('[role="alert"]').text()).toContain('暂时无法收集，请重试')
  expect(wrapper.find('[data-result]').exists()).toBe(false)
  await click('重试')
  expect(wrapper.get('[data-testid="retry-list"]').attributes('disabled')).toBeDefined()
  await click('重试')
  expect(wrapper.get('[aria-label="收集状态"]').text()).toBe('收集中 · 请求 2 次')
  await vi.advanceTimersByTimeAsync(700)
  expect(wrapper.get('[data-result]').attributes('data-status')).toBe('success')
  expect(wrapper.get('[data-result]').text()).toContain('收到了 3 条回响')
  await click('查看失败结果')
  expect(wrapper.get('[data-result]').attributes('data-status')).toBe('error')
  await click('重新收集')
  expect(wrapper.get('[aria-label="收集状态"]').text()).toBe('收集中 · 请求 3 次')
  await click('清空回响')
  await vi.advanceTimersByTimeAsync(1000)
  expect(wrapper.get('[data-slot="empty"]').text()).toContain('尚未收集回响')
  expect(wrapper.get('[aria-label="收集状态"]').text()).toBe('尚未收集 · 请求 0 次')
})
it('shows badge count, cap, dot and a removable slot tag without inventing an unknown zero', async () => {
  wrapper = mount(MobileFeedbackDemo)
  expect(wrapper.get('[data-slot="badge"]').text()).toContain('7')
  await click('超过上限')
  expect(wrapper.get('[data-slot="badge"]').text()).toContain('9+')
  await click('仅显示圆点')
  expect(wrapper.get('[aria-label="提醒数值"]').text()).toBe('有新回响，数量未知')
  expect(wrapper.get('[data-slot="badge"]').text()).not.toContain('9+')
  await click('没有未读')
  expect(wrapper.get('[aria-label="提醒数值"]').text()).toBe('未读 0 条')
  expect(wrapper.get('[data-slot="badge"]').findAll('span')).toHaveLength(1)
  await wrapper.get('[aria-label="移除标签"]').trigger('click')
  expect(wrapper.get('[aria-label="标签回显"]').text()).toBe('已移除「周末」')
  await click('恢复标签')
  expect(wrapper.get('[data-slot="tag"]').text()).toContain('周末')
})
it('auto hides toast, updates a persistent loading toast, restarts duration and permits host close', async () => {
  vi.useFakeTimers()
  wrapper = mount(MobileFeedbackDemo)
  await click('短暂提示')
  expect(document.body.textContent).toContain('已记住这一刻')
  await vi.advanceTimersByTimeAsync(1200)
  expect(wrapper.get('[aria-label="提示状态"]').text()).toBe('已关闭')
  await click('持续等待')
  await vi.advanceTimersByTimeAsync(3000)
  expect(document.body.querySelector('[data-type="loading"]')).not.toBeNull()
  await click('更新为成功')
  expect(document.body.querySelector('[data-type="success"]')).not.toBeNull()
  await vi.advanceTimersByTimeAsync(600)
  await click('延长提示')
  await vi.advanceTimersByTimeAsync(700)
  expect(wrapper.get('[aria-label="提示状态"]').text()).toBe('显示中 · success · 2400ms')
  await vi.advanceTimersByTimeAsync(1700)
  expect(wrapper.get('[aria-label="提示状态"]').text()).toBe('已关闭')
  await click('持续等待')
  await click('关闭提示')
  expect(document.body.querySelector('[role="status"]')).toBeNull()
})
it('keeps unknown and failed progress distinct from finite values and toggles loaded skeleton content', async () => {
  wrapper = mount(MobileFeedbackDemo)
  expect(wrapper.get('[aria-label="进度状态"]').text()).toBe('进度未知，等待开始')
  expect(wrapper.find('[role="progressbar"]').exists()).toBe(false)
  await click('开始整理')
  expect(wrapper.get('[role="progressbar"]').attributes('aria-valuenow')).toBe('0')
  expect(wrapper.findAll('[data-slot="skeleton"]')).toHaveLength(3)
  await click('整理到一半')
  expect(wrapper.get('[role="progressbar"]').attributes('aria-valuenow')).toBe('50')
  await click('整理失败')
  expect(wrapper.get('[aria-label="进度状态"]').text()).toBe('整理失败，进度不可用')
  expect(wrapper.find('[role="progressbar"]').exists()).toBe(false)
  await click('完成整理')
  expect(wrapper.get('[role="progressbar"]').attributes('aria-valuenow')).toBe('100')
  expect(wrapper.find('[data-slot="skeleton"]').exists()).toBe(false)
  expect(wrapper.text()).toContain('湖畔的风，已收入手记。')
  await click('未知进度')
  expect(wrapper.find('[role="progressbar"]').exists()).toBe(false)
})
it('changes real image and avatar URLs after failure and preserves their independent fallback slots', async () => {
  wrapper = mount(MobileFeedbackDemo)
  const image = () => wrapper.get('[data-slot="mobile-image"]')
  await image().get('img').trigger('load')
  expect(image().get('img').classes()).toContain('opacity-100')
  await click('损坏的风景')
  expect(image().get('img').attributes('src')).toBe('/media/missing-landscape.png')
  await image().get('img').trigger('error')
  expect(image().text()).toContain('加载失败')
  await click('换一张风景')
  expect(image().text()).not.toContain('加载失败')
  expect(image().get('img').attributes('src')).toContain('meadow.svg')
  await image().get('img').trigger('load')
  expect(image().get('img').classes()).toContain('opacity-100')
  await click('损坏的头像')
  await wrapper.get('[data-live-avatar] img').trigger('error')
  expect(wrapper.get('[data-live-avatar]').text()).toBe('林悦')
  await click('恢复头像')
  expect(wrapper.get('[data-live-avatar] img').attributes('src')).toContain('portrait.svg')
  expect(wrapper.get('[data-slot-avatar]').text()).toBe('旅')
})
it('cancels pending host work and toast timers when the page is removed', async () => {
  vi.useFakeTimers()
  wrapper = mount(MobileFeedbackDemo)
  await vi.runOnlyPendingTimersAsync()
  await click('收集回响')
  await click('短暂提示')
  expect(vi.getTimerCount()).toBe(2)
  wrapper.unmount()
  expect(vi.getTimerCount()).toBe(0)
  await vi.advanceTimersByTimeAsync(3000)
  expect(document.body.querySelector('.nv-m-toast-layer')).toBeNull()
})
it('cancels the old collection when an external result replaces a pending request', async () => {
  vi.useFakeTimers()
  wrapper = mount(MobileFeedbackDemo)
  await click('收集回响')
  await click('查看失败结果')
  await vi.advanceTimersByTimeAsync(1000)
  expect(wrapper.get('[data-result]').attributes('data-status')).toBe('error')
  expect(wrapper.get('[aria-label="收集状态"]').text()).toBe('结果失败 · 请求 1 次')
  await click('重新收集')
  await vi.advanceTimersByTimeAsync(700)
  expect(wrapper.get('[data-result]').attributes('data-status')).toBe('success')
})
