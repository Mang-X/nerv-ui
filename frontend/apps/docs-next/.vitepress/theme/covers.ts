/** 四个色调：品牌是默认，其余三种只用在「状态」上。 */
const TONES = [color.brand, color.success, color.warning, color.danger] as const

/** 把形状元组转成给模板用的属性。 */
export function shapeProps(shape: Shape) {
  const [kind, ...n] = shape
  // 最后一个元素可能是 tone，也可能不存在；按 kind 判断这次是否带了 tone。
  const hasTone = { f: 7, s: 7, l: 6, d: 5, r: 5 }[kind] === n.length
  const colorOf = (index: number) => TONES[hasTone ? (n[index] as Tone) : 0]

  switch (kind) {
    case 'f':
      return {
        type: 'rect' as const,
        x: n[0],
        y: n[1],
        w: n[2],
        h: n[3],
        rx: n[4],
        opacity: n[5],
        fill: true,
        color: colorOf(6),
      }
    case 's':
      return {
        type: 'rect' as const,
        x: n[0],
        y: n[1],
        w: n[2],
        h: n[3],
        rx: n[4],
        opacity: n[5],
        fill: false,
        color: colorOf(6),
      }
    case 'l':
      return {
        type: 'line' as const,
        x1: n[0],
        y1: n[1],
        x2: n[2],
        y2: n[3],
        opacity: n[4],
        color: colorOf(5),
      }
    case 'd':
      return {
        type: 'circle' as const,
        cx: n[0],
        cy: n[1],
        r: n[2],
        opacity: n[3],
        fill: true,
        color: colorOf(4),
      }
    case 'r':
      return {
        type: 'circle' as const,
        cx: n[0],
        cy: n[1],
        r: n[2],
        opacity: n[3],
        fill: false,
        color: colorOf(4),
      }
    case 'p':
      return {
        type: 'path' as const,
        d: n[0],
        opacity: n[1],
        fill: n[2] === 1,
        width: n[3] ?? 1.25,
        color: TONES[(n[4] as Tone | undefined) ?? 0],
      }
  }
}

