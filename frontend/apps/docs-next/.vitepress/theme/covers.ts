/**
 * 组件封面：每个组件一张 120×80 的示意图形，画的是这个组件自己的骨架。
 *
 * 两个约束决定了它的画法：
 * 1. 只用 currentColor 加透明度——卡片把颜色设成品牌色，亮暗两套主题
 *    共用同一份图形，不需要为暗色再画一遍。
 * 2. 图形是「结构示意」不是「截图」：几条圆角块就能认出表格、滑块、日历，
 *    不需要真实文字，也就不会在切换主题或缩放时糊掉。
 *
 * 词表很小，所有封面都从这五种形状拼出来，因此一屏十几张卡看起来是同一套。
 */
export type Shape =
  /** 实心圆角块：fill(x, y, w, h, radius, opacity) */
  | ['f', number, number, number, number, number, number]
  /** 描边圆角块：stroke(x, y, w, h, radius, opacity) */
  | ['s', number, number, number, number, number, number]
  /** 直线：line(x1, y1, x2, y2, opacity) */
  | ['l', number, number, number, number, number]
  /** 实心圆点：dot(cx, cy, r, opacity) */
  | ['d', number, number, number, number]
  /** 描边圆环：ring(cx, cy, r, opacity) */
  | ['r', number, number, number, number]

const f = (x: number, y: number, w: number, h: number, radius = 2, opacity = 0.18): Shape => [
  'f',
  x,
  y,
  w,
  h,
  radius,
  opacity,
]
const s = (x: number, y: number, w: number, h: number, radius = 2, opacity = 0.42): Shape => [
  's',
  x,
  y,
  w,
  h,
  radius,
  opacity,
]
const l = (x1: number, y1: number, x2: number, y2: number, opacity = 0.32): Shape => [
  'l',
  x1,
  y1,
  x2,
  y2,
  opacity,
]
const d = (cx: number, cy: number, r: number, opacity = 0.45): Shape => ['d', cx, cy, r, opacity]
const ring = (cx: number, cy: number, r: number, opacity = 0.42): Shape => ['r', cx, cy, r, opacity]

/** 一行「文字」：细条，用于表现文本区。 */
const text = (x: number, y: number, w: number, opacity = 0.16) => f(x, y, w, 3, 1.5, opacity)

